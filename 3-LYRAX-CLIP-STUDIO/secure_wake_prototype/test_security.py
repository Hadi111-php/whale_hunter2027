# -*- coding: utf-8 -*-
"""
🧪 تست امنیتی واقعی: سه نوع حمله به سیستم «چشم و دست + مرکز کنترل» شبیه‌سازی‌شده می‌زنیم
و با چاپ نتیجه‌ی واقعی (نه ادعا) بررسی می‌کنیم آیا سیستم جلوشون رو می‌گیره یا نه.
"""

import copy
import time
import sys
sys.path.insert(0, '/home/user/secure_wake_prototype')

from device_agent import DeviceAgent
from control_center import ControlCenter, SecurityError


def line(title):
    print("\n" + "=" * 70)
    print(title)
    print("=" * 70)


# ==========================================================================
# راه‌اندازی اولیه: یک گوشی واقعی + مرکز کنترل
# ==========================================================================
line("🔧 راه‌اندازی: ثبت‌نام گوشی واقعی نزد مرکز")

center = ControlCenter()
phone = DeviceAgent(device_id="phone-real-001", center_public_key_hex=center.center_public_key_bytes)
center.register_device(phone.device_id, phone.public_key_bytes)
print(f"گوشی واقعی ساخته شد. کلید عمومی (فقط این به مرکز داده می‌شود): {phone.public_key_bytes[:24]}...")
print("کلید خصوصی هرگز از گوشی خارج نشد (شبیه‌سازی Secure Enclave).")

# ==========================================================================
# سناریوی پایه: کاربر دستی گوشی را بیدار می‌کند و یک درخواست معتبر می‌فرستد
# ==========================================================================
line("✅ سناریوی پایه: کاربر دستی بیدار می‌کند و یک درخواست عادی می‌فرستد")

phone.wake_up()
block1 = phone.build_signed_request({"mission": "بررسی وضعیت باتری"})
result1 = center.receive_block(block1)
print("نتیجه:", result1)
phone.sleep()
print("گوشی دوباره خوابید. is_awake =", phone.is_awake)

# بلوک دوم معتبر (برای اینکه زنجیره حداقل ۲ بلوک داشته باشه قبل از حمله)
phone.wake_up()
block2 = phone.build_signed_request({"mission": "دانلود آپدیت امنیتی"})
result2 = center.receive_block(block2)
print("نتیجه بلوک دوم:", result2)
phone.sleep()

assert result1["status"] == "accepted" and result2["status"] == "accepted"
print("\n✅✅ سناریوی پایه با موفقیت کار کرد.")


# ==========================================================================
# حمله‌ی ۱: Replay Attack — همان بلوک قبلی (کاملاً معتبر) را دوباره می‌فرستیم
# ==========================================================================
line("🔁 حمله‌ی ۱: Replay Attack (ارسال دوباره‌ی یک درخواست قدیمیِ کاملاً معتبر)")

print("هکر یک بسته‌ی شبکه (block2) را که قبلاً بین گوشی و مرکز رد و بدل شده، ضبط کرده")
print("و همان‌طور که هست (بدون هیچ تغییری، امضا هم واقعی و درسته) دوباره برای مرکز ارسال می‌کند...")

try:
    center.receive_block(block2)  # همون بلوک قبلی، بدون تغییر
    print("❌❌❌ خطرناک! سیستم این حمله را قبول کرد!")
except SecurityError as e:
    print(f"✅ سیستم جلوی حمله را گرفت. پیام رد شدن: {e}")


# ==========================================================================
# حمله‌ی ۲: Tampering — محتوای یک بلوک قدیمی را عوض می‌کنیم (مثلاً ماموریت را عوض می‌کنیم)
# ==========================================================================
line("✂️ حمله‌ی ۲: Tampering (دستکاری محتوای یک درخواست)")

print("هکر سعی می‌کند یک بلوک جدید بسازد ولی محتوای payload را عوض کند")
print("بدون این‌که امضای واقعی گوشی را داشته باشد (چون کلید خصوصی را ندارد)...")

# هکر یک بلوک جدید طبیعی از گوشی می‌گیرد و بعد از تولید، محتوایش را دستکاری می‌کند
# (شبیه‌سازی: یک نفر وسط راه بسته را گرفته و payload را عوض کرده)
# نکته: این بلوک را عمداً به مرکز *نمی‌فرستیم* مگر نسخه‌ی دستکاری‌شده را، بنابراین شماره‌ی
# index واقعی‌اش (که در زنجیره‌ی محلی گوشی مصرف شده) را برای ادامه‌ی تست کنار می‌گذاریم
# و به‌جایش خودِ همین بلوک اصلی (بدون دستکاری) را هم در انتها به مرکز می‌فرستیم تا زنجیره پیوسته بماند.
phone.wake_up()
legit_block = phone.build_signed_request({"mission": "بررسی وضعیت شبکه"})
phone.sleep()

tampered_block = copy.deepcopy(legit_block)
tampered_block["payload"] = {"mission": "پاک کردن تمام فایل‌های کاربر!! 😈"}  # محتوای مخرب جایگزین شد
# توجه: hash و signature همان مقادیر قبلی (مال payload اصلی) باقی مانده، چون هکر کلید خصوصی ندارد

try:
    center.receive_block(tampered_block)
    print("❌❌❌ خطرناک! سیستم دستکاری را تشخیص نداد!")
except SecurityError as e:
    print(f"✅ سیستم جلوی حمله را گرفت. پیام رد شدن: {e}")

# حالا نسخه‌ی *اصلی و دست‌نخورده*‌ی همین بلوک را به مرکز می‌فرستیم تا زنجیره طبیعی ادامه پیدا کند
r_legit = center.receive_block(legit_block)
print("ارسال نسخه‌ی اصلی (بدون دستکاری) همان بلوک:", r_legit)


# ==========================================================================
# حمله‌ی ۳: Forge — یک گوشی جعلی (هکر) بدون کلید خصوصی واقعی سعی می‌کند جای گوشی واقعی جا بزند
# ==========================================================================
line("🎭 حمله‌ی ۳: Forge (جعل هویت با یک کلید جعلی/متفاوت)")

fake_phone = DeviceAgent(device_id="phone-real-001")  # همون device_id رو ادعا می‌کنه ولی کلید خصوصیش فرق داره!
print("هکر یک 'گوشی جعلی' با کلید خصوصی خودش می‌سازد اما وانمود می‌کند device_id همان گوشی واقعی است...")

fake_phone.wake_up()
forged_block = fake_phone.build_signed_request({"mission": "ارسال اطلاعات بانکی به سرور هکر"})
fake_phone.sleep()

try:
    center.receive_block(forged_block)
    print("❌❌❌ خطرناک! سیستم جعل هویت را تشخیص نداد!")
except SecurityError as e:
    print(f"✅ سیستم جلوی حمله را گرفت. پیام رد شدن: {e}")


# ==========================================================================
# حمله‌ی ۴ (بونوس): حذف یک بلوک از وسط زنجیره و ادامه دادن با بلوک بعدی
# ==========================================================================
line("🕳️ حمله‌ی ۴ (بونوس): حذف یک بلوک از وسط زنجیره (Chain Gap Attack)")

phone.wake_up()
block3 = phone.build_signed_request({"mission": "درخواست معتبر شماره سه"})
block4 = phone.build_signed_request({"mission": "درخواست معتبر شماره چهار"})
phone.sleep()

print(f"گوشی دو بلوک پشت‌سرهم (index={block3['index']} و index={block4['index']}) تولید کرده.")
print("هکر بلوک اول را قایم می‌کند و فقط بلوک دوم را می‌فرستد")
print("(شاید بخواهد وانمود کند بلوک اول اصلاً وجود نداشته یا آن را بعداً با محتوای دیگری جایگزین کند)...")

try:
    center.receive_block(block4)  # بدون اینکه block3 قبلش پذیرفته شده باشه
    print("❌❌❌ خطرناک! سیستم گپ زنجیره را تشخیص نداد!")
except SecurityError as e:
    print(f"✅ سیستم جلوی حمله را گرفت. پیام رد شدن: {e}")

# حالا بلوک ۳ را به‌درستی می‌فرستیم و بعد بلوک ۴ - باید هر دو قبول شوند
print("\nحالا بلوک‌ها را به ترتیب درست می‌فرستیم:")
r3 = center.receive_block(block3)
print("بلوک اول:", r3)
r4 = center.receive_block(block4)
print("بلوک دوم:", r4)



line("📊 خلاصه‌ی نهایی")
print(f"تعداد بلوک‌های تأییدشده در زنجیره‌ی مرکز برای گوشی واقعی: {len(center.device_chains[phone.device_id])}")
print("همه‌ی ۴ نوع حمله شبیه‌سازی و تست شد. نتایج بالا را ببین داداش گلم 👆")
