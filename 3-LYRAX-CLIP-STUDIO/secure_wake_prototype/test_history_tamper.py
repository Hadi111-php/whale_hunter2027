import sys
sys.path.insert(0, '/home/user/secure_wake_prototype')

from device_agent import DeviceAgent
from control_center import ControlCenter, SecurityError

print("=" * 70)
print("🧨 سناریو: هکر گوشی را در دست می‌گیرد و سعی می‌کند زنجیره‌ی محلی ذخیره‌شده")
print("   (تاریخچه‌ی بلوک‌های قبلی که هنوز برای مرکز نفرستاده) را عوض کند")
print("=" * 70)

center = ControlCenter()
phone = DeviceAgent(device_id="phone-002", center_public_key_hex=center.center_public_key_bytes)
center.register_device(phone.device_id, phone.public_key_bytes)

# سه بلوک عادی و معتبر تولید می‌شود (هنوز به مرکز نرسیده - مثلاً گوشی موقتاً آفلاین بوده)
phone.wake_up()
b0 = phone.build_signed_request({"mission": "گزارش سلامت سیستم"})
b1 = phone.build_signed_request({"mission": "دریافت لیست ماموریت‌های جدید"})
b2 = phone.build_signed_request({"mission": "اجرای اسکریپت پاکسازی کش"})
phone.sleep()

print(f"\nگوشی سه بلوک تولید کرده: index={b0['index']},{b1['index']},{b2['index']} - هنوز هیچ‌کدام ارسال نشده.")

print("\n🔓 حالا فرض کنید گوشی قفلش باز مانده و هکر به فایل ذخیره‌شده‌ی زنجیره (b1) دسترسی پیدا کرده")
print("   و می‌خواهد قبل از ارسال، ماموریت وسط زنجیره را عوض کند (مثلاً به یک ماموریت مخرب):")

# هکر مستقیماً محتوای بلوک وسط (b1) را که هنوز روی دیسک/حافظه ذخیره است دستکاری می‌کند
b1_hacked = dict(b1)
b1_hacked["payload"] = {"mission": "ارسال مخفیانه‌ی مخاطبین به سرور ناشناس"}
# او hash/signature قدیمی را دست‌نخورده می‌گذارد چون کلید خصوصی گوشی را ندارد و نمی‌تواند امضای جدید بسازد

print("\n1️⃣ ارسال بلوک اول (b0) - دست‌نخورده:")
r0 = center.receive_block(b0)
print("   نتیجه:", r0)

print("\n2️⃣ ارسال بلوک دوم دستکاری‌شده (b1_hacked) به‌جای b1 اصلی:")
try:
    center.receive_block(b1_hacked)
    print("   ❌❌❌ خطرناک! مرکز این را قبول کرد!")
except SecurityError as e:
    print(f"   ✅ مرکز رد کرد: {e}")

print("\n3️⃣ حالا فرض کنیم هکر منصرف شد و b1 اصلی (دست‌نخورده) را فرستاد:")
r1 = center.receive_block(b1)
print("   نتیجه:", r1)

print("\n4️⃣ و در آخر b2 اصلی را می‌فرستیم؛ باید زنجیره سالم باشد چون b0 و b1 هر دو دست‌نخورده بودند:")
r2 = center.receive_block(b2)
print("   نتیجه:", r2)

print("\n" + "=" * 70)
print("📌 نتیجه‌گیری داداش گلم:")
